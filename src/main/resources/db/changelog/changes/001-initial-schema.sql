--changeset hernando:002-create-time-slots-table
CREATE SEQUENCE time_slots_id_seq START WITH 1 INCREMENT BY 50;

CREATE TABLE time_slots
(
    id         BIGINT                   NOT NULL DEFAULT nextval('time_slots_id_seq') PRIMARY KEY,
    user_id    BIGINT                   NOT NULL
        CONSTRAINT fk_time_slots_user REFERENCES users (id) ON DELETE CASCADE,
    start_time TIMESTAMP WITH TIME ZONE NOT NULL,
    end_time   TIMESTAMP WITH TIME ZONE NOT NULL,
    status     VARCHAR(20)              NOT NULL,
    version    BIGINT                   NOT NULL DEFAULT 0
);

CREATE INDEX idx_time_slots_user_start_end ON time_slots (user_id, start_time, end_time);
CREATE INDEX idx_time_slots_start_end_status ON time_slots (start_time, end_time, status);

